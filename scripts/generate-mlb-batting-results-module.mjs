import fs from 'node:fs'
import fsp from 'node:fs/promises'
import path from 'node:path'
import { gunzipSync } from 'node:zlib'

const root = path.resolve(import.meta.dirname, '..')

const argValue = (name, fallback = '') => {
  const prefix = `${name}=`
  const inline = process.argv.find((arg) => arg.startsWith(prefix))
  if (inline) return inline.slice(prefix.length)
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : fallback
}

const parseDates = () =>
  String(argValue('--dates') || argValue('--date'))
    .split(',')
    .map((date) => date.trim())
    .filter(Boolean)

const forceFinalGamePks = new Set(
  String(argValue('--force-final-game-pks') || '')
    .split(',')
    .map((value) => Number(value.trim()))
    .filter(Number.isFinite)
)

const readJsonGz = (filePath) => JSON.parse(gunzipSync(fs.readFileSync(filePath)).toString('utf8'))

const playerRowsForSide = ({ date, gameTitle, gamePk, side, teamBoxscore }) => {
  const teamName = teamBoxscore?.team?.teamName || teamBoxscore?.team?.name || ''
  const players = Object.values(teamBoxscore?.players || {})
  return players
    .map((player) => {
      const batting = player?.stats?.batting || {}
      const atBats = Number(batting.atBats || 0)
      const plateAppearances = Number(batting.plateAppearances || 0)
      const hits = Number(batting.hits || 0)
      const runs = Number(batting.runs || 0)
      const rbi = Number(batting.rbi || 0)
      const homeRuns = Number(batting.homeRuns || 0)
      const walks = Number(batting.baseOnBalls || 0) + Number(batting.intentionalWalks || 0)
      const totalBases = Number(batting.totalBases || 0)
      if (!atBats && !plateAppearances && !hits && !runs && !rbi && !homeRuns && !walks && !totalBases) return null
      return {
        date,
        gamePk,
        gameTitle,
        teamSide: side,
        teamName,
        playerId: player?.person?.id ?? null,
        playerName: player?.person?.fullName || player?.person?.boxscoreName || '',
        atBats,
        plateAppearances,
        hits,
        runs,
        rbi,
        homeRuns,
        walks,
        totalBases,
        hitRunRbi: hits + runs + rbi
      }
    })
    .filter((row) => row && row.playerName)
}

const rowsForDate = (date) => {
  const gamesRoot = path.join(root, 'data-private', 'raw', 'mlb', date, 'games')
  if (!fs.existsSync(gamesRoot)) return []
  return fs.readdirSync(gamesRoot)
    .filter((fileName) => fileName.endsWith('-feed-live.json.gz'))
    .flatMap((fileName) => {
      const feed = readJsonGz(path.join(gamesRoot, fileName))
      const gamePk = feed?.gameData?.game?.pk ?? feed?.gamePk ?? null
      if (feed?.gameData?.status?.abstractGameState !== 'Final' && !forceFinalGamePks.has(Number(gamePk))) return []
      const awayName = feed?.gameData?.teams?.away?.teamName || ''
      const homeName = feed?.gameData?.teams?.home?.teamName || ''
      const gameTitle = `${awayName} @ ${homeName}`
      const boxscore = feed?.liveData?.boxscore?.teams || {}
      return [
        ...playerRowsForSide({ date, gameTitle, gamePk, side: 'away', teamBoxscore: boxscore.away }),
        ...playerRowsForSide({ date, gameTitle, gamePk, side: 'home', teamBoxscore: boxscore.home })
      ]
    })
}

const main = async () => {
  const dates = parseDates()
  if (!dates.length) throw new Error('Pass --dates YYYY-MM-DD[,YYYY-MM-DD].')
  const rows = dates.flatMap(rowsForDate)
  const outPath = path.join(root, 'web', 'src', 'lib', 'mlb-batting-results.generated.js')
  await fsp.mkdir(path.dirname(outPath), { recursive: true })
  await fsp.writeFile(
    outPath,
    `// Generated by scripts/generate-mlb-batting-results-module.mjs\nexport const mlbBattingResultsRows = ${JSON.stringify(rows, null, 2)};\n`,
    'utf8'
  )
  console.log(`Wrote ${rows.length} MLB batting result rows for ${dates.join(', ')} -> ${outPath}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
